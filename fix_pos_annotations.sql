-- 为什么文件名不叫 seed_*.sql：
--   logos/db/connection.py 的 SEED_GLOB = "seed_*.sql" 会把命中文件当成种子
--   自动加载进所有走 init_database 的管线（e2e、解析器测试…），那会连带改变
--   下游所有测试的 ID 空间与计数。本文件是**覆盖式修正**，必须显式触发。
--
-- 幂等性：全部是 UPDATE ... WHERE pos <> 'n'，重复执行改动 0 行。
-- 生命周期：重新播种（apply_seeds.py）会用种子里的 pos 覆盖本修正，
--          之后需要再次执行本文件或带 --fix-pos 跑推理。
