PRAGMA foreign_keys = ON;

BEGIN;

-- -----------------------------------------------------------------------------
-- 1) 「防御」—— 行为类别，被误标为动词 v
-- -----------------------------------------------------------------------------
-- 证据（实测）：
--   * 作为 can_do 的**源**出现 3 次：防御 can_do 伪装 / 变色 / 喷射推进
--   * 作为 can_do 的**目标**出现 18 次：猴子 can_do 防御 …
--   即它在库里是一个「行为类别」名词（defense 这一活动类型），与
--   「运动 / 捕猎 / 通讯 / 育幼 …」同类，而不是动词。
--
-- 注意：本条修正在**写入行数**上不改变任何推断结果（实测 154 -> 154 行），
-- 但它确实动了守卫：
--   1. pos 不是模型特征（prototype_gat 只把 pos 存进 graph.pos_tags 供打印）；
--   2. can_do 的源侧分布 n:109/v:37 -> n:112/v:34，两档都远高于 5%，源侧守卫仍不触发；
--   3. can_do 的**目标**侧原本是 v:146/146（100%），而「防御」正是其中 18 条边的目标。
--      改标后目标侧变成 v:128/n:18，n 占 12.3% >= 0.05 —— 目标词性白名单里多了一个 n，
--      候选池多放行 87 条（13,702 -> 13,615 条被剔除）。
-- 也就是说：**can_do 目标侧 100% 是动词这件事，有一部分是这个错误标注撑起来的。**
-- 这与「修正标注」并不矛盾 —— 恰恰说明真正的缺陷是 can_do 同时承载了两个方向
-- （动物→行为类别 / 行为类别→具体动作），单个词性维度承载不了。
-- 它的价值在于让标注自洽，而不是提高过滤率。
UPDATE senses
   SET pos = 'n'
 WHERE pos <> 'n'
   AND sense_id IN (
        SELECT s.sense_id FROM senses s
          JOIN words w ON w.word_id = s.word_id
         WHERE w.word = '防御'
   );

COMMIT;

